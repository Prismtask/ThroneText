def verify_all_cities_mapped(cities_dict: dict) -> list:
    """Cross-reference with cities.CITIES and return list of missing keys."""
    from resources.cities import CITIES
    mapped = set(CITY_MAPS.keys())
    defined = set(CITIES.keys())
    missing = defined - mapped
    extra = mapped - defined
    result = []
    if missing:
        result.append(f"MISSING maps for: {sorted(missing)}")
    if extra:
        result.append(f"EXTRA maps (not in CITIES): {sorted(extra)}")
    return result if result else ["All cities have maps. OK"]


