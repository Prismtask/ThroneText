"""
City ASCII Maps
───────────────
Wide-format ASCII maps optimized for GUI display.
Each map is ~80 chars wide, ~12-18 lines tall.
No name banners, no travel connection labels — pure environmental art.

Usage:
    from resources.city_maps import get_city_map, list_city_maps, CITY_MAPS

    map_art = get_city_map("solmere")
    print(map_art)
"""

from typing import Optional


def get_city_map(city_key: str) -> Optional[str]:
    """Return the ASCII map for *city_key* (lowercase, e.g. 'solmere').
    Returns None if the city is unknown."""
    return CITY_MAPS.get(city_key.lower())


def list_city_maps() -> list:
    """Return a sorted list of all city keys that have an ASCII map."""
    return sorted(CITY_MAPS.keys())


def get_city_map_by_name(city_name: str) -> Optional[str]:
    """Look up a city map by its display name (case-insensitive)."""
    for key, art in CITY_MAPS.items():
        if art.strip().startswith(city_name):
            return art
    return None


CITY_MAPS: dict[str, str] = {}

